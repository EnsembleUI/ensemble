/// Pure Dart check used before launching any Flutter benchmark process.
void checkInstrumentedOperations(Directory package) {
  final pattern = RegExp(
      r"RunnerBenchmark\.(?:sync|async|future|pending)\(\s*'([^']+)',\s*'([^']+)'",
      multiLine: true);
  final found = <String>{};
  for (final file
      in Directory('${package.path}/lib').listSync(recursive: true)) {
    if (file is! File || !file.path.endsWith('.dart')) continue;
    for (final match in pattern.allMatches(file.readAsStringSync())) {
      found.add('${match[1]}.${match[2]}');
    }
  }
  final missing = found.difference(operationCases.keys.toSet());
  final stale = operationCases.keys.toSet().difference(found);
  if (missing.isNotEmpty || stale.isNotEmpty) {
    throw StateError(
        'Benchmark operation coverage drift: missing=$missing stale=$stale');
  }
}
