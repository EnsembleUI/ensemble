import 'package:path/path.dart' as p;

/// Pure source transformations used when preparing an application test entry.
///
/// Keeping these operations independent from filesystem mutation makes entry
/// adaptation deterministic and keeps [TestAppPatcher] focused on lifecycle
/// and rollback behavior.
class EntrySourceTransformer {
  const EntrySourceTransformer._();

  /// Entry points accepted by the application and standalone launchers.
  ///
  static const applicationWidgetEntryPoints = <String>[
    'runApplicationTests',
  ];
  static const applicationIntegrationEntryPoints = <String>[
    'runApplicationIntegrationTests',
  ];
  static const ensembleWidgetEntryPoints = <String>[
    'runEnsembleTests',
  ];
  static const ensembleIntegrationEntryPoints = <String>[
    'runEnsembleIntegrationTests',
  ];
  static const applicationEntryPoints = <String>[
    ...applicationWidgetEntryPoints,
    ...applicationIntegrationEntryPoints,
  ];
  static const integrationEntryPoints = <String>[
    ...ensembleIntegrationEntryPoints,
    ...applicationIntegrationEntryPoints,
  ];

  static const _integrationEntryPointReplacements = <String, String>{
    'runEnsembleTests': 'runEnsembleIntegrationTests',
    'runApplicationTests': 'runApplicationIntegrationTests',
  };

  /// Creates a thin integration entry that preserves imports from the source.
  static String applicationIntegrationWrapperContents(
    String widgetEntryRelative,
  ) {
    final importUri = posixRelativeImportUri(
      fromFile:
          'integration_test/${p.posix.basename(widgetEntryRelative.replaceAll('\\', '/'))}',
      toFile: widgetEntryRelative.replaceAll('\\', '/'),
    );
    return '''
// Generated by ensemble_test_runner — do not edit.
import '$importUri' as application_tests;

Future<void> main() => application_tests.main();
''';
  }

  /// Rewrites relative Dart imports when a file is copied to a new folder.
  static String relocateDartImports({
    required String source,
    required String fromRelative,
    required String toRelative,
  }) {
    return source.replaceAllMapped(
      RegExp(r'''^(\s*import\s+)(['"])([^'"]+)\2(.*)$''', multiLine: true),
      (match) {
        final uri = match.group(3)!;
        if (uri.startsWith('dart:') ||
            uri.startsWith('package:') ||
            uri.startsWith('http:') ||
            uri.startsWith('https:')) {
          return match.group(0)!;
        }
        final fromDir = p.posix.dirname(fromRelative.replaceAll('\\', '/'));
        final resolved = p.posix.normalize(p.posix.join(fromDir, uri));
        final relocated = posixRelativeImportUri(
          fromFile: toRelative.replaceAll('\\', '/'),
          toFile: resolved,
        );
        return '${match.group(1)}${match.group(2)}$relocated${match.group(2)}${match.group(4)}';
      },
    );
  }

  /// Dart import URI from [fromFile] to [toFile], both app-root relative.
  static String posixRelativeImportUri({
    required String fromFile,
    required String toFile,
  }) {
    final fromDir = p.posix.dirname(fromFile.replaceAll('\\', '/'));
    final relative = p.posix.relative(
      p.posix.normalize(toFile.replaceAll('\\', '/')),
      from: fromDir,
    );
    return relative.startsWith('.') ? relative : './$relative';
  }

  /// Adapter next to [widgetEntryRelative] so `import 'foo.dart'` still works.
  static String applicationIntegrationAdapterRelativePath(
    String widgetEntryRelative,
  ) {
    final normalized = widgetEntryRelative.replaceAll('\\', '/');
    final dir = p.posix.dirname(normalized);
    final base = p.posix.basenameWithoutExtension(normalized);
    final ext = p.posix.extension(normalized);
    return p.posix.join(dir, '$base.integration$ext');
  }

  /// Whether [source] invokes [functionName] outside comments.
  static bool entryPointCallsFunction(String source, String functionName) {
    final stripped = _entryDetectionSource(source);
    return RegExp('\\b${RegExp.escape(functionName)}\\s*\\(')
        .hasMatch(stripped);
  }

  /// Returns whether source calls at least one supported entry point.
  static bool entryPointCallsAny(
    String source,
    Iterable<String> functionNames,
  ) {
    final names = functionNames.map(RegExp.escape).toList(growable: false);
    if (names.isEmpty) return false;
    final stripped = _entryDetectionSource(source);
    return RegExp('\\b(?:${names.join('|')})\\s*\\(').hasMatch(stripped);
  }

  /// Removes comments and string literals for entry-point detection.
  ///
  /// A host source may mention a runner function in an import, diagnostic
  /// string, or generated marker. Those mentions must not make the patcher
  /// treat the file as executable test entry code.
  static String _entryDetectionSource(String source) {
    final withoutComments = stripDartComments(source);
    final buffer = StringBuffer();
    var i = 0;
    while (i < withoutComments.length) {
      final quote = withoutComments[i];
      if (quote != "'" && quote != '"') {
        buffer.write(quote);
        i++;
        continue;
      }
      buffer.write(' ');
      i++;
      while (i < withoutComments.length) {
        final ch = withoutComments[i];
        if (ch == '\\' && i + 1 < withoutComments.length) {
          buffer.write('  ');
          i += 2;
          continue;
        }
        if (ch == quote) {
          buffer.write(' ');
          i++;
          break;
        }
        buffer.write(ch == '\n' ? '\n' : ' ');
        i++;
      }
    }
    return buffer.toString();
  }

  /// Removes `//` and `/* */` comments for entry-point validation.
  static String stripDartComments(String source) {
    final buffer = StringBuffer();
    var i = 0;
    while (i < source.length) {
      if (i + 1 < source.length && source[i] == '/' && source[i + 1] == '/') {
        i += 2;
        while (i < source.length && source[i] != '\n') i++;
        continue;
      }
      if (i + 1 < source.length && source[i] == '/' && source[i + 1] == '*') {
        i += 2;
        while (i + 1 < source.length &&
            !(source[i] == '*' && source[i + 1] == '/')) {
          i++;
        }
        i = i + 2 < source.length ? i + 2 : source.length;
        continue;
      }
      if (source[i] == "'" || source[i] == '"') {
        final quote = source[i];
        buffer.write(quote);
        i++;
        while (i < source.length) {
          final ch = source[i];
          buffer.write(ch);
          if (ch == '\\' && i + 1 < source.length) {
            buffer.write(source[i + 1]);
            i += 2;
            continue;
          }
          if (ch == quote) {
            i++;
            break;
          }
          i++;
        }
        continue;
      }
      buffer.write(source[i]);
      i++;
    }
    return buffer.toString();
  }

  /// Converts a supported widget entry to an integration entry.
  ///
  /// Returns `null` when the source does not invoke a supported entry point.
  /// Detection happens after rewriting so strings and comments cannot make an
  /// unrelated file appear to be an entry. Returning the source unchanged is
  /// valid when it already invokes an integration entry point.
  static String? adaptEntryForIntegration(String source) {
    var adapted = source.replaceAll(
      'package:ensemble_test_runner/entry/ensemble_test_entry.dart',
      'package:ensemble_test_runner/entry/ensemble_integration_test_entry.dart',
    );
    adapted = adapted.replaceAll(
      'package:ensemble_test_runner/entry/application_test_entry.dart',
      'package:ensemble_test_runner/entry/application_integration_test_entry.dart',
    );
    for (final replacement in _integrationEntryPointReplacements.entries) {
      adapted =
          adapted.replaceAll('${replacement.key}(', '${replacement.value}(');
    }
    return entryPointCallsAny(
      adapted,
      _integrationEntryPointReplacements.values,
    )
        ? adapted
        : null;
  }
}
